/** The icon set, inline.
 *
 * No icon package. The project had none installed, adding one costs a
 * dependency and a bundle for the seventeen glyphs actually used, and
 * these are a few hundred bytes of path data that never needs a version
 * bump. They follow the same drawing conventions as Lucide — 24×24 grid,
 * 2px stroke, round caps and joins — so swapping to `lucide-react` later
 * is a find-and-replace, not a redesign.
 *
 * Every icon is `aria-hidden`. An icon is never the accessible name:
 * whatever wraps it carries the label, so a screen reader hears "Review
 * inbox", not "inbox icon Review inbox".
 */

